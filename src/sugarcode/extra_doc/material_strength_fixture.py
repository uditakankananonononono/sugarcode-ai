"""Row 1528, Materials Selection.

material_strength_fixture requires supplied strength count x meeting
minimum and ranks candidates by supplied cost y ascending, strength
descending, label ascending. Returns candidates (label,strength,cost),
excluded sorted and best label or None. No actual materials recommendation,
property validation, physical units, manufacturability or safety claim.
Inputs: rows is an exact list or tuple of 1 to 8 entries. Each entry is an
exact list or tuple (label, x, y). label is an exact printable ASCII str
of 1 to 12 characters, unique across rows. x and y are exact ints from
0 to 10; bool and all subclasses are refused.
minimum defaults to 4, an exact int from 0 to 10.
Validation order: rows type, rows size, minimum, then each row in input
order (shape, label, x, y), then duplicate labels.
NOT_CLAIMED: materials recommendation, property validation, physical units, engineering safety, production readiness.
"""

SCOPE = 'PARTIAL: supplied strength/cost count feasible ranking, no materials recommendation'
NOT_CLAIMED = ('materials recommendation', 'property validation', 'physical units', 'engineering safety', 'production readiness')


def _label(x):
    return type(x) is str and x.isascii() and x.isprintable() and 1 <= len(x) <= 12


def material_strength_fixture(rows, minimum=4):
    if type(rows) not in (list, tuple):
        raise TypeError('rows must be a list or tuple')
    if not 1 <= len(rows) <= 8:
        raise ValueError('rows must contain 1 to 8 entries')
    if type(minimum) is not int or not 0 <= minimum <= 10:
        raise ValueError('minimum must be a nonbool integer between 0 and 10')
    clean = []
    for row in rows:
        if type(row) not in (list, tuple) or len(row) != 3:
            raise ValueError('each row must be a (label, x, y) triple')
        label, x, y = row
        if not _label(label):
            raise ValueError('label must be a printable ASCII string of 1 to 12 characters')
        if type(x) is not int or not 0 <= x <= 10:
            raise ValueError('x must be a nonbool integer between 0 and 10')
        if type(y) is not int or not 0 <= y <= 10:
            raise ValueError('y must be a nonbool integer between 0 and 10')
        clean.append((label, x, y))
    if len({r[0] for r in clean}) != len(clean):
        raise ValueError('labels must be distinct')
    values=sorted(((n,x,y) for n,x,y in clean if x>=minimum),key=lambda r:(r[2],-r[1],r[0]))
    return {'candidates':values,'excluded':sorted(n for n,x,y in clean if x<minimum),
            'best':values[0][0] if values else None}
